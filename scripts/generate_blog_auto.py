try:
    from PIL import Image
    import pytesseract
except Exception:
    Image = None
    pytesseract = None


def detect_unwanted_text(img_path: Path) -> bool:
    """OCR 检测图片中任意可识别文字（中英文/数字字母/水印词）。命中则判失败。"""
    if not Image or not pytesseract:
        return False
    if not shutil.which("tesseract"):
        return False
    try:
        img = Image.open(img_path).convert("RGB")
        w, h = img.size
        rois = [
            img,  # 全图
            img.crop((0, int(h * 0.72), w, h)),  # 底部常见水印区
        ]
        texts = []
        for roi in rois:
            raw = pytesseract.image_to_string(roi, lang="chi_sim+eng")
            texts.append(raw)
        merged = "\n".join(texts)
        merged_upper = merged.upper()

        if any(k in merged_upper for k in WATERMARK_HINTS):
            return True
        if TEXT_PATTERN.search(merged):
            return True
        return False
    except Exception:
        return False


