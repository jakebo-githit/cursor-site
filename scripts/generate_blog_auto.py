def generate_siliconflow_image(topic_type: str, slug: str) -> str:
    """使用 SiliconFlow 生成配图，保存到本地并返回相对路径。"""
    fallback_map = {
        "gallbladder": "/images/gallstone-prevention.jpg",
        "liver": "/images/liver-health.jpg",
        "longevity": "/images/dietary-guidance.jpg",
        "nutrition": "/images/dietary-guidance.jpg",
        "default": "/images/recovery-guide.jpg",
    }

    if not SILICONFLOW_API_KEY:
        print("[WARN] SILICONFLOW_API_KEY not set, using fallback image.")
        return fallback_map.get(topic_type, "/images/pocs-surgery.jpg")

    prompt = IMAGE_PROMPTS.get(topic_type, IMAGE_PROMPTS["default"]) + "; strict constraints: no text, no letters, no Chinese characters, no symbols, no logo, no watermark, no signature, no calligraphy, no ancient style, no traditional Chinese painting, no fantasy scene, no moon palace aesthetics, no blood, no gore, no wounds, no frightening scene, no pain-expression close-up, no graphic surgery close-up; keep calm, clean, reassuring medical education tone."

    for model_name in SILICONFLOW_IMAGE_MODELS:
        for attempt in range(1, 3):
            try:
                payload = {
                    "model": model_name,
                    "prompt": prompt,
                    "image_size": "1280x720",  # 16:9 横版，适合博客封面
                }
                resp = requests.post(
                    SILICONFLOW_BASE_URL,
                    headers={
                        "Authorization": f"Bearer {SILICONFLOW_API_KEY}",
                        "Content-Type": "application/json",
                    },
                    json=payload,
                    timeout=120,
                )
                resp.raise_for_status()
                data = resp.json().get("data", [])
                if not data:
                    raise RuntimeError("No image data from SiliconFlow")

                if data[0].get("url"):
                    img_resp = requests.get(data[0]["url"], timeout=60)
                    img_resp.raise_for_status()
                    img_bytes = img_resp.content
                elif data[0].get("b64_json"):
                    import base64
                    img_bytes = base64.b64decode(data[0]["b64_json"])
                else:
                    raise RuntimeError("No image URL/base64 from SiliconFlow")

                img_filename = f"blog-{slug[:40]}.jpg"
                img_path = IMAGES_DIR / img_filename
                img_path.write_bytes(img_bytes)

                if detect_unwanted_text(img_path):
                    print(f"[WARN] Text/watermark detected ({model_name}, attempt {attempt}), retrying...")
                    try:
                        img_path.unlink(missing_ok=True)
                    except Exception:
                        pass
                    continue

                print(f"[OK] AIGC image saved: {img_filename} via {model_name}")
                return f"/images/blog/{img_filename}"
            except Exception as ex:
                print(f"[WARN] SiliconFlow image failed ({model_name}, attempt {attempt}): {ex}")
                continue

    return fallback_map.get(topic_type, "/images/pocs-surgery.jpg")


# ─────────────────────────── Save Markdown ───────────────────────────
def save_markdown(slug: str, data: dict, image_url: str, source_url: str):
    today = datetime.now().strftime("%Y-%m-%d")

    # Chinese markdown file
    zh_path = BLOG_MD_DIR / f"{slug}.md"
    zh_header = f"""---
title: {data['title']}
date: {today}
category: {data['category']}
image: {image_url}
source: {source_url}
---

"""
    zh_path.write_text(zh_header + data["markdownZh"].strip() + "\n", encoding="utf-8")

    # English markdown file
    en_path = BLOG_MD_DIR / f"{slug}-en.md"
    en_header = f"""---
title: {data['titleEn']}
date: {today}
category: {data['categoryEn']}
image: {image_url}
source: {source_url}
---

"""
    en_path.write_text(en_header + data["markdownEn"].strip() + "\n", encoding="utf-8")

    print(f"[OK] Saved: {zh_path.name} + {en_path.name}")
    return str(zh_path), str(en_path)


# ─────────────────────────── Update blog-posts.ts ───────────────────────────
def update_blog_index(slug: str, data: dict, image_url: str):
    """Insert new post entry into src/data/blog-posts.ts"""
    today = datetime.now().strftime("%Y-%m-%d")

    esc = lambda s: (s or "").replace("'", "\\'")
    title = esc(data.get("title", ""))
    title_en = esc(data.get("titleEn", ""))
    excerpt = esc(data.get("excerpt", ""))
    excerpt_en = esc(data.get("excerptEn", ""))
    category = esc(data.get("category", ""))
    category_en = esc(data.get("categoryEn", ""))

    new_entry = f"""  {{
    id: '{slug}',
    title: '{title}',
    titleEn: '{title_en}',
    excerpt: '{excerpt}',
    excerptEn: '{excerpt_en}',
    date: '{today}',
    category: '{category}',
    categoryEn: '{category_en}',
    imageUrl: '{image_url}',
    author: 'AskDrLiu.com'
  }},"""

    content = BLOG_INDEX_FILE.read_text(encoding="utf-8")

    # Insert after "export const blogPosts: BlogPost[] = ["
    marker = "export const blogPosts: BlogPost[] = ["
    if marker not in content:
        print("[WARN] Could not find blogPosts array marker. Skipping auto-insert.")
        print(f"[INFO] Manually add this entry:\n{new_entry}")
        return

    insert_pos = content.index(marker) + len(marker)
    # Skip any whitespace/newline after marker
    new_content = content[:insert_pos] + "\n" + new_entry + content[insert_pos:]
    BLOG_INDEX_FILE.write_text(new_content, encoding="utf-8")
    print(f"[OK] Registered in blog-posts.ts: {slug}")


# ─────────────────────────── Main ───────────────────────────
def make_slug(title: str) -> str:
    """Generate a URL-friendly slug from Chinese or English title."""
    # Remove non-alphanumeric (keep spaces)
    clean = re.sub(r"[^\w\s-]", "", title, flags=re.UNICODE)
    clean = re.sub(r"\s+", "-", clean.strip()).lower()
    # Limit length and add random suffix
    clean = clean[:40]
    suffix = "".join(random.choices(string.ascii_lowercase + string.digits, k=6))
    today = datetime.now().strftime("%Y%m%d")
    return f"{today}-{clean}-{suffix}" if clean else f"{today}-post-{suffix}"


